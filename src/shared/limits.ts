/**
 * 跨进程共享的用量上限。
 *
 * 单独一个模块是因为 types.ts 明确只放类型;这些是运行时常量,主进程要用
 * 它做硬性拦截,渲染层要用同一个数字给用户提示——两边各写一份迟早会对不上。
 */

/**
 * 一次最多附带多少个文件。
 *
 * 不是技术限制,是**用法上的分界**:超过十个说明用户想让 AI 了解的是一个
 * "项目"而不是几份材料。那种情况授权目录、让 AI 自己按需检索,比把文件
 * 一个个塞进来更省 token,也更容易找到真正相关的部分。
 */
export const MAX_FILES_AT_ONCE = 10

/**
 * 单轮工具调用的默认硬上限,0 表示不限。
 *
 * 曾经写死 40,复杂一点的改动跑一半就被熔断。放到配置里之后这个数只是
 * 默认值:主进程按它派生三档阈值,设置页要用它当占位提示。
 */
export const DEFAULT_TOOL_CALL_LIMIT = 80
