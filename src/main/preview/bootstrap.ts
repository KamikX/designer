/**
 * Bootstrap HTML for Vue 3 / React iframes; HTML projects serve user files directly.
 *
 * The host generates this page rather than AI so mounting, error reporting, and
 * Tailwind injection remain predictable. Core runtimes use preview://vendor/*
 * without network dependencies; selected component libraries use the CDN below.
 *
 * No compiler runs inside the iframe.
 *
 * Previously this embedded vue3-sfc-loader (1.8 MB), Babel (2.4 MB), and custom
 * CommonJS require and dependency crawling. SFC / JSX compilation now happens in
 * the main process (compile.ts), with preview:// serving ES modules. The iframe needs:
 *
 * 1. A native import map pointing bare imports (Vue / React) to vendor ESM files.
 * 2. Mounting code such as `import('./App.vue')`.
 *
 * The browser requests relative imports such as `./Foo.vue` directly from the
 * protocol handler, so no dependency crawling, registry, or evaluation ordering is needed.
 *
 * Electron 43's Chromium supports import maps natively; no es-module-shims is needed.
 */

/**
 * Bare-import mappings.
 *
 * Adding a core dependency requires an entry here and an ESM asset copied or
 * generated by scripts/prepare-preview-vendor.mjs. Unlike vue3-sfc-loader, this
 * keeps new dependencies independent of loader internals.
 */
const VENDOR_IMPORTS: Record<string, string> = {
  vue: 'preview://vendor/vue.esm.js',
  react: 'preview://vendor/react.esm.js',
  'react/jsx-runtime': 'preview://vendor/react-jsx-runtime.esm.js',
  'react/jsx-dev-runtime': 'preview://vendor/react-jsx-runtime.esm.js',
  'react-dom': 'preview://vendor/react-dom.esm.js',
  // React 18 exposes createRoot through react-dom/client, but both paths share
  // the same object in the UMD build, so they can use the same vendor file.
  'react-dom/client': 'preview://vendor/react-dom.esm.js'
}

/** @param extra Project-level mappings allow user-selected dependencies. */
export function buildImportMap(extra?: Record<string, string>): string {
  const imports = { ...VENDOR_IMPORTS, ...extra }
  return `<script type="importmap">${JSON.stringify({ imports })}</script>`
}

