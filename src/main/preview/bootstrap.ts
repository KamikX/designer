/**
 * Pin versions rather than using latest so saved previews remain reproducible.
 * Upgrades require updating the version constants and following docs/preview-libs.md.
 *
 * Dependency closure verified against antdv-next-playground:
 * - antd.esm.js only imports "vue" as a bare dependency. dayjs and its six plugins,
 *   cssinjs, and @v-c/util are bundled. Do not map dayjs separately: a second instance
 *   would not share locale and plugin state.
 * - Vue must be >= 3.5 because the bundle uses onWatcherCleanup, and it must share
 *   the page's instance; the vendor Vue mapping ensures this.
 * - dist/antd.esm.js requires antdv-next >= 1.0.4.
 * - Icon dependencies, including @ant-design/colors, are bundled too and need no mappings.
 */
const LIB_CDN = 'https://cdn.jsdelivr.net/npm/'

function libImports(libs: PreviewLib[]): Record<string, string> {
  const imports: Record<string, string> = {}
  if (libs.includes('antdv-next')) {
    const base = `${LIB_CDN}antdv-next@${LIB_VERSIONS['antdv-next']}`
    imports['antdv-next'] = `${base}/dist/antd.esm.js`
    // A trailing-slash mapping allows subpaths such as antdv-next/dist/locale/zh_CN.js.
    // It only replaces the prefix; omitting the .js extension still produces a 404.
    imports['antdv-next/'] = `${base}/`
  }
  if (libs.includes('@antdv-next/icons')) {
    const base = `${LIB_CDN}@antdv-next/icons@${LIB_VERSIONS['@antdv-next/icons']}`
    imports['@antdv-next/icons'] = `${base}/dist/antd-icons.esm.js`
    imports['@antdv-next/icons/'] = `${base}/`
  }
  return imports
}

/*
 * Styles and app.use registration belong to each library's virtual setup module
 * (`__setup__/<name>.js`, see lib-setup.ts), awaited in selection order.
 * Setup loads CSS through <link> load/error events so a CDN failure reports the
 * exact URL instead of silently displaying an unstyled page.
 */

/**
 * Design token injection.
 *
 * Tailwind v4's browser runtime needs the @theme block from theme.css inside
 * <style type="text/tailwindcss"> to compile it into utility classes.
 *
 * Inline the theme while generating HTML in the main process. An asynchronous
 * iframe fetch could finish after Tailwind scans the DOM, causing an unstyled
 * first frame; inlining avoids that timing issue.
 */
function themeTag(theme: string | undefined): string {
  if (!theme?.trim()) return ''
  // Strip duplicate Tailwind imports to avoid conflicting with the built-in runtime.
  // Older artifacts and model output may still include them despite prompt restrictions.
  const cleaned = theme.replace(/@import\s+(['"])tailwindcss\1\s*;?/g, '')
  return `<style type="text/tailwindcss">\n${cleaned}\n</style>`
}

const COMMON_HEAD = `
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<script src="preview://vendor/tailwind.js"></script>
<style>html, body, #app { min-height: 100%; } body { margin: 0; }</style>
<script>
  // Some libraries, including React builds, read process.env and need a shim to avoid ReferenceError.
  window.process = window.process || { env: { NODE_ENV: 'production' } }

  function reportError(message) {
    parent.postMessage({ __preview: true, type: 'error', message: String(message) }, '*')
  }
  window.onerror = function (msg, _src, _line, _col, err) {
    reportError((err && err.stack) || msg)
  }
  window.addEventListener('unhandledrejection', function (e) {
    reportError((e.reason && (e.reason.stack || e.reason.message)) || e.reason)
  })

  /*
   * Tell the parent when it can remove the loading skeleton.
   *
   * The iframe load event can fire before Vue / React finishes loading its module
   * graph and mounting. Removing the skeleton then would expose a blank page.
   *
   * Two animation frames allow layout and painting to finish before removing the
   * overlay, avoiding a blank flash while mounted content is still waiting to paint.
   */
  function notifyReady() {
    requestAnimationFrame(function () {
      requestAnimationFrame(function () {
        parent.postMessage({ __preview: true, type: 'ready' }, '*')
      })
    })
  }
  // HTML has no mounting step, so load signals readiness. Vue / React set this flag
  // to true and signal readiness after mounting instead.
  window.__previewAwaitMount = false
  window.addEventListener('load', function () {
    if (!window.__previewAwaitMount) notifyReady()
  })
</script>
${ANNOTATE_RUNTIME}
`

/**
 * Mounting scripts.
 *
 * Dynamic imports inside try/catch let module failures (404s, compilation errors,
 * syntax errors) reach reportError, the preview panel, and model feedback. Static
 * top-level imports could fail before the handler runs, leaving only a console
 * error and a blank preview.
 */
const vueBoot = (
  setups: string[],
  withAntd: boolean,
  lang: Lang,
  appSetup?: 'app.setup.ts' | 'app.setup.js'
): string => `
<script type="module">
  window.__previewAwaitMount = true
  try {
    const { createApp } = await import('vue')
    const App = (await import('./App.vue')).default
    if (!App) throw new Error(${JSON.stringify(translate(lang, 'preview.vueRootRequired'))})
    const app = createApp(App)
    ${setups
      .map(
        (
          path
        ) => `// Virtual library setup stays outside artifact files so generated code cannot alter it.
    await (await import(${JSON.stringify(path)})).default(app)`
      )
      .join('\n    ')}
    ${
      appSetup
        ? `const setup = (await import(${JSON.stringify(`./${appSetup}`)})).default
    if (typeof setup !== 'function') throw new Error('Project app setup must default-export a function: ${appSetup}')
    await setup(app)`
        : ''
    }
    app.mount('#app')
    ${
      withAntd
        ? ''
        : `/*
     * Production Vue silently renders unregistered <a-xxx> components as ordinary
     * elements, with object props becoming [object Object]. Scan after mounting
     * so a missing antdv-next selection produces actionable feedback for the user
     * and model instead of a silently broken page.
     */
    const stray = [...document.querySelectorAll('#app *')].find(
      (el) => el.tagName.toLowerCase().startsWith('a-')
    )
    if (stray) {
      reportError(
        ${JSON.stringify(translate(lang, 'preview.missingAntdvNext'))}.replace('{0}', stray.tagName.toLowerCase())
      )
    }`
    }
    notifyReady()
  } catch (err) {
    reportError((err && err.stack) || err.message || err)
  }
</script>
`

const reactBoot = (lang: Lang): string => `
<script type="module">
  window.__previewAwaitMount = true
  try {
    const React = (await import('react')).default
    const { createRoot } = await import('react-dom/client')
    /*
     * Try .tsx first, then .jsx: TypeScript is the current default, but older
     * JavaScript artifacts must still render instead of showing a blank preview
     * solely because the default changed.
     */
    let mod
    try {
      mod = await import('./App.tsx')
    } catch {
      mod = await import('./App.jsx')
    }
    const App = mod.default || mod.App
    if (!App) throw new Error(${JSON.stringify(translate(lang, 'preview.reactRootRequired'))})
    createRoot(document.getElementById('app')).render(React.createElement(App))
    notifyReady()
  } catch (err) {
    reportError((err && err.stack) || err.message || err)
  }
</script>
`

export function buildBootstrapHtml(
  stack: Stack,
  theme?: string,
  libs: PreviewLib[] = [],
  external: InstalledLibrary[] = [],
  lang: Lang = 'zh-CN',
  appSetup?: 'app.setup.ts' | 'app.setup.js'
): string {
  // Component library setup only supports Vue 3; other stacks must not load it.
  const activeLibs = stack === 'vue3' ? libs : []
  let boot =
    stack === 'vue3'
      ? vueBoot(libSetupPaths(activeLibs), activeLibs.includes('antdv-next'), lang, appSetup)
      : reactBoot(lang)
  const extra: Record<string, string> = {}
  const styles: string[] = []
  for (const lib of external) {
    for (const [spec, file] of Object.entries(lib.entries))
      extra[spec] = `./__libraries__/${lib.id}/${file}`
    styles.push(...lib.styles.map((file) => `./__libraries__/${lib.id}/${file}`))
  }
  if (styles.length) {
    boot = boot.replace(
      '  try {',
      `  try {
    await Promise.all(${JSON.stringify(styles)}.map(href => new Promise((resolve, reject) => {
      const link = document.createElement('link'); link.rel = 'stylesheet'; link.href = href;
      link.onload = resolve; link.onerror = () => reject(new Error('Library stylesheet failed: ' + href));
      document.head.append(link);
    })))`
    )
  }
  // The import map must precede every module script so bare imports can resolve.
  return `<!doctype html>
<html>
<head>${buildImportMap({ ...libImports(activeLibs), ...extra })}${COMMON_HEAD}${themeTag(theme)}</head>
<body>
<div id="app"></div>
${boot}
</body>
</html>`
}

/**
 * HTML projects serve user HTML with Tailwind and error reporting injected.
 * Prefer insertion before </head>, falling back to <body> or the document start
 * so fragments without a complete document structure still receive the runtime.
 *
 * Do not inject an import map: user HTML may already define one, and the host
 * does not control its module imports. Avoid conflicts with the user's mappings.
 */
export function injectHtmlRuntime(html: string, theme?: string): string {
  const inject = COMMON_HEAD + themeTag(theme)
  if (html.includes('</head>')) return html.replace('</head>', `${inject}</head>`)
  if (html.includes('<body')) return html.replace('<body', `${inject}<body`)
  return inject + html
}
