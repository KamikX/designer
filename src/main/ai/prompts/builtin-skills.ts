import { DESIGN_SYSTEM_SKILL } from './design-system'

/**
 * 内置技能。
 *
 * 放在代码里而不是种进数据库,理由有三:
 * - 随应用升级自动更新,不用写迁移,也不会出现"老用户还在用旧规范"
 * - 用户删不掉、改不坏——设计体系规范是产品的骨架,不是可选项
 * - 不用给 skills 表加 isBuiltin 字段
 *
 * `alwaysOn` 的技能对所有会话强制生效;其余的将来可以放进技能面板让用户
 * 按会话勾选,与用户自己导入的技能同等对待。
 */

export interface BuiltinSkill {
  id: string
  name: string
  description: string
  content: string
  /** 强制注入,用户不可关闭 */
  alwaysOn: boolean
}

/**
 * 交互与状态完备性。
 *
 * 单独成一条而不是并进设计体系:设计体系管"长什么样",这条管"漏没漏东西"。
 * AI 产出的设计稿最常见的缺陷不是不好看,是只画了理想路径——列表永远有
 * 三条数据,按钮永远可点,请求永远成功。
 */
const INTERACTION_SKILL = `
# 交互完备性(强制)

设计稿最容易漏的不是样式,是**除理想路径之外的所有情况**。交付前逐条对一遍:

## 数据的四种状态

任何展示数据的区域都要想清楚这四种:

- **有数据**:注意长内容。名字可能很长、数字可能很大、列表可能有 200 条。
  长文本要么截断加省略号,要么换行,不能把布局撑破。
- **空**:第一次进来什么都没有。要有图形 + 一句说明 + 一个明确的下一步按钮。
  "暂无数据"四个灰字是不合格的。
- **加载中**:用骨架屏,形状要贴合真实内容的布局。列表就是几条灰条,卡片
  就是卡片的轮廓。不要用居中转圈——那会让页面在加载完的瞬间跳一下。
- **出错**:说清楚发生了什么、用户能做什么。要有重试入口。

## 边界数量

列表设计要同时交代 1 条、3 条、和"很多条"分别长什么样。只有一条时不该
看起来像出了 bug;很多条时要有分页、虚拟滚动或者"加载更多"。

## 交互反馈

- 点击后有变化:按钮进入 loading、内容立刻更新、或者出提示。不能点了没反应
- 破坏性操作(删除、清空)要二次确认,确认按钮用危险色
- 表单校验在失焦时触发,不要在用户还没输完就报错
- 提交中要禁用提交按钮,防重复提交

## 响应式

至少交代两个断点:窄屏(≤640px)和常规。窄屏下:
- 多列变单列,侧栏收起或变成底部导航
- 表格改成卡片列表,或者允许横向滚动但要有滚动提示
- 可点区域放大到 44×44
`.trim()

